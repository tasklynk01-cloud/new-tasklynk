#!/usr/bin/env tsx
/**
 * Combined Setup Script for Phases 1-4 (Critical Phases)
 * 
 * This script runs all critical phase setup scripts in sequence.
 * Run: tsx scripts/setup-phases-1-4.ts
 */

import * as fs from 'fs';
import * as path from 'path';
import { execSync } from 'child_process';

async function combinePhases() {
  console.log('\n');
  console.log('╔════════════════════════════════════════════════════════════╗');
  console.log('║  Setting Up Critical Phases 1-4                          ║');
  console.log('╚════════════════════════════════════════════════════════════╝');
  console.log('\n');

  const phases = [
    { name: 'Phase 1: Core Application Settings', script: 'setup-phase-1-core.ts' },
    { name: 'Phase 2: Security & Authentication', script: 'setup-phase-2-security.ts' },
    { name: 'Phase 3: Database Configuration', script: 'setup-phase-3-database.ts' },
    { name: 'Phase 4: Email Configuration', script: 'setup-phase-4-email.ts' },
  ];

  const envFiles: string[] = [];

  for (const phase of phases) {
    console.log(`\n🔄 Running ${phase.name}...`);
    console.log('─'.repeat(60));
    
    try {
      execSync(`tsx scripts/${phase.script}`, { stdio: 'inherit' });
      envFiles.push(`.env.${phase.script.replace('setup-phase-', '').replace('.ts', '')}`);
      console.log(`✅ ${phase.name} completed`);
    } catch (error) {
      console.error(`❌ ${phase.name} failed`);
      console.error('Please fix the error and run again');
      process.exit(1);
    }
  }

  // Combine all phase files
  console.log('\n');
  console.log('╔════════════════════════════════════════════════════════════╗');
  console.log('║  Combining Phase Configurations                           ║');
  console.log('╚════════════════════════════════════════════════════════════╝');
  console.log('\n');

  let combinedContent = '# TaskLynk Environment Configuration\n';
  combinedContent += '# Generated by setup-phases-1-4.ts\n';
  combinedContent += '# Date: ' + new Date().toISOString() + '\n\n';

  for (const envFile of envFiles) {
    const filePath = path.join(process.cwd(), envFile);
    if (fs.existsSync(filePath)) {
      const content = fs.readFileSync(filePath, 'utf-8');
      combinedContent += content + '\n';
    }
  }

  // Save combined file
  const combinedPath = path.join(process.cwd(), '.env.phases-1-4');
  fs.writeFileSync(combinedPath, combinedContent);

  console.log('✅ All phases completed!');
  console.log(`\n📁 Combined configuration saved to: .env.phases-1-4`);
  console.log('\n📋 Next Steps:');
  console.log('   1. Review .env.phases-1-4 file');
  console.log('   2. Copy values to your .env file:');
  console.log('      cat .env.phases-1-4 >> .env');
  console.log('   3. Or copy to your deployment platform (Vercel/Netlify)');
  console.log('   4. Verify configuration: npm run verify-env');
  console.log('   5. Continue with Phase 5: File Storage');
  console.log('\n⚠️  SECURITY NOTE:');
  console.log('   - Never commit .env files to version control');
  console.log('   - Keep secrets secure');
  console.log('   - Use different values for dev/prod');
  console.log('');
}

combinePhases().catch(console.error);

