#!/usr/bin/env tsx
/**
 * Complete Setup Script for All Phases
 * 
 * This script runs all phase setup scripts in sequence.
 * Phases 1-5 are critical, Phases 6-10 are optional/important.
 * 
 * Run: tsx scripts/setup-all-phases.ts
 */

import * as fs from 'fs';
import * as path from 'path';
import { execSync } from 'child_process';

const phases = [
  // Critical Phases
  { 
    number: 1, 
    name: 'Core Application Settings', 
    script: 'setup-phase-1-core.ts', 
    priority: 'critical',
    required: true 
  },
  { 
    number: 2, 
    name: 'Security & Authentication', 
    script: 'setup-phase-2-security.ts', 
    priority: 'critical',
    required: true 
  },
  { 
    number: 3, 
    name: 'Database Configuration', 
    script: 'setup-phase-3-database.ts', 
    priority: 'critical',
    required: true 
  },
  { 
    number: 4, 
    name: 'Email Configuration', 
    script: 'setup-phase-4-email.ts', 
    priority: 'critical',
    required: true 
  },
  { 
    number: 5, 
    name: 'File Storage (Cloudinary)', 
    script: 'setup-phase-5-storage.ts', 
    priority: 'critical',
    required: true 
  },
  // Optional/Important Phases
  { 
    number: 6, 
    name: 'M-Pesa Payment Gateway', 
    script: 'setup-phase-6-mpesa.ts', 
    priority: 'important',
    required: false 
  },
  { 
    number: 7, 
    name: 'Paystack Payment Gateway', 
    script: 'setup-phase-7-paystack.ts', 
    priority: 'important',
    required: false 
  },
  { 
    number: 8, 
    name: 'Supabase (Secondary Storage)', 
    script: 'setup-phase-8-supabase.ts', 
    priority: 'optional',
    required: false 
  },
  { 
    number: 9, 
    name: 'Feature Flags & Performance', 
    script: 'setup-phase-9-features.ts', 
    priority: 'optional',
    required: false 
  },
  { 
    number: 10, 
    name: 'Monitoring & Analytics', 
    script: 'setup-phase-10-monitoring.ts', 
    priority: 'optional',
    required: false 
  },
];

async function setupAllPhases() {
  console.log('\n');
  console.log('╔════════════════════════════════════════════════════════════╗');
  console.log('║  Complete Environment Setup - All Phases                 ║');
  console.log('╚════════════════════════════════════════════════════════════╝');
  console.log('\n');

  console.log('This will guide you through all configuration phases:');
  console.log('');
  console.log('🔴 CRITICAL (Phases 1-5) - Required for basic functionality');
  console.log('🟡 IMPORTANT (Phases 6-7) - Required for payments');
  console.log('🟢 OPTIONAL (Phases 8-10) - Enhanced features');
  console.log('');

  const envFiles: string[] = [];
  const completedPhases: number[] = [];
  const skippedPhases: number[] = [];

  for (const phase of phases) {
    console.log(`\n${'═'.repeat(60)}`);
    console.log(`Phase ${phase.number}: ${phase.name} (${phase.priority})`);
    console.log('═'.repeat(60));
    
    const scriptPath = path.join(process.cwd(), 'scripts', phase.script);
    
    // Check if script exists
    if (!fs.existsSync(scriptPath)) {
      console.log(`⚠️  Script not found: ${phase.script}`);
      console.log('   Skipping this phase...');
      skippedPhases.push(phase.number);
      continue;
    }

    try {
      execSync(`tsx scripts/${phase.script}`, { stdio: 'inherit' });
      
      const envFile = `.env.phase${phase.number}`;
      if (fs.existsSync(path.join(process.cwd(), envFile))) {
        envFiles.push(envFile);
      }
      
      completedPhases.push(phase.number);
      console.log(`✅ Phase ${phase.number} completed`);
    } catch (error) {
      console.error(`❌ Phase ${phase.number} failed`);
      
      if (phase.required) {
        console.error('This is a critical phase. Setup cannot continue.');
        process.exit(1);
      } else {
        console.log('This phase is optional. Continuing...');
        skippedPhases.push(phase.number);
      }
    }
  }

  // Combine all phase files
  console.log('\n');
  console.log('╔════════════════════════════════════════════════════════════╗');
  console.log('║  Combining All Configurations                             ║');
  console.log('╚════════════════════════════════════════════════════════════╝');
  console.log('\n');

  let combinedContent = '# TaskLynk Environment Configuration - Complete\n';
  combinedContent += '# Generated by setup-all-phases.ts\n';
  combinedContent += `# Date: ${new Date().toISOString()}\n`;
  combinedContent += `# Completed Phases: ${completedPhases.join(', ')}\n`;
  if (skippedPhases.length > 0) {
    combinedContent += `# Skipped Phases: ${skippedPhases.join(', ')}\n`;
  }
  combinedContent += '\n';

  for (const envFile of envFiles) {
    const filePath = path.join(process.cwd(), envFile);
    if (fs.existsSync(filePath)) {
      const content = fs.readFileSync(filePath, 'utf-8');
      combinedContent += content + '\n';
    }
  }

  // Save combined file
  const combinedPath = path.join(process.cwd(), '.env.complete');
  fs.writeFileSync(combinedPath, combinedContent);

  console.log('✅ Setup complete!');
  console.log(`\n📁 Combined configuration saved to: .env.complete`);
  console.log(`\n✅ Completed Phases: ${completedPhases.length}/${phases.length}`);
  console.log(`   ${completedPhases.map(n => `Phase ${n}`).join(', ')}`);
  
  if (skippedPhases.length > 0) {
    console.log(`\n⚠️  Skipped Phases: ${skippedPhases.length}`);
    console.log(`   ${skippedPhases.map(n => `Phase ${n}`).join(', ')}`);
  }

  console.log('\n📋 Next Steps:');
  console.log('   1. Review .env.complete file');
  console.log('   2. Copy to your .env file:');
  console.log('      cp .env.complete .env');
  console.log('   3. Or copy to deployment platform');
  console.log('   4. Verify configuration:');
  console.log('      npm run verify-env');
  console.log('   5. Start application:');
  console.log('      npm run dev');
  console.log('\n⚠️  SECURITY NOTE:');
  console.log('   - Never commit .env files to version control');
  console.log('   - Keep secrets secure');
  console.log('   - Use different values for dev/prod');
  console.log('');
}

setupAllPhases().catch((error) => {
  console.error('\n❌ Setup failed:', error.message);
  process.exit(1);
});

